# Invert the len-41 branch of easyre.
# forward: out[(13*i)%41] = (rol8(key_a[i%8]^key_b[i%8]^inp[i], (i%7)+1) + ((11*i)^0x23)) & 0xff
target = bytes([0x23,0x05,0x79,0x1b,0x6c,0xc1,0x84,0x0f,0x88,0xb2,0x7d,0xeb,0xa0,0x7e,0xf4,0x32,
                0xc6,0xf5,0x70,0xc1,0xc5,0x26,0xbf,0x16,0xdd,0x42,0x36,0x3a,0x6a,0x6a,0x45,0x17,
                0xf4,0x4c,0xcd,0x84,0xae,0x27,0x8c,0xc8,0x38])
key_a = bytes([0x19,0xa4,0xc7,0x52,0x6e,0x01,0x9b,0xf0])
key_b = bytes([0x5b,0x75,0xb4,0x7b,0xcb,0x5d,0x73,0xe6])
ror8 = lambda v,r: ((v>>(r&7))|(v<<(8-(r&7))))&0xff
flag = bytearray(41)
for i in range(41):
    t = target[(13*i)%41]
    t = (t - ((11*i) ^ 0x23)) & 0xff
    t = ror8(t, (i%7)+1)
    flag[i] = t ^ key_a[i%8] ^ key_b[i%8]
print(flag.decode('latin1'))
